export type SkillBranchId = 'core' | 'physical' | 'mental' | 'social' | 'lifestyle';

export interface UnifiedSkillNode {
  id: string;
  branchId: 'physical' | 'mental' | 'social' | 'lifestyle' | 'core';
  branchName: string;
  subBranch?: string; // e.g. 'Endurance', 'Strength', 'Focus', 'Knowledge', 'Communication', 'Leadership'
  title: string;
  subtitle: string;
  description: string;
  tier: number; // 0 to 6
  maxLevel: number; // 1 or 2
  spCost: number; // Universal Skill Points
  prerequisiteId?: string;
  pillarId: PillarId;
  primaryStatId: StatId;
  unlockedAbility: string;
  questTypes: string[]; // Displayed in detail panel
  questTags: string[]; // Quest tags this node enables/weights in the quest generator
  domain: DevelopmentDomain | 'general_maintenance';
  icon: string; // Lucide icon name
  bonusXpPercent?: number; // e.g. +10% XP
  statBonusText?: string; // e.g. 'Endurance XP Gain +10%'
  requiredPlayerLevel?: number;
  requiredSkillId?: string;
  requiredSkillLevel?: number;
  requiredSkillName?: string;
  isMastery?: boolean;
  isRoot?: boolean;
  isBranchHub?: boolean;
  // Node coordinates on the RPG Canvas
  x: number;
  y: number;
}

export interface SkillBranch {
  id: 'core' | 'physical' | 'mental' | 'social' | 'lifestyle';
  name: string;
  tagline: string;
  color: string;
  accentColor: string;
  borderColor: string;
  bgGradient: string;
  icon: string;
}

