/**
 * Enrichment function to ensure full taxonomy, concept IDs, variation families,
 * and category capabilities across all quest library items.
 */
function enrichLibraryItem(item: QuestLibraryItem): QuestLibraryItem {
  const parts = item.id.split('_');
  const conceptKey = item.conceptId || (parts.length >= 2 ? `${parts[0]}_${parts[1]}` : item.id);
  const variationFamily = item.variationFamily || (parts.length >= 2 ? parts[1] : item.domain);

  let cat = item.category;
  if (!cat) {
    if (item.rarity === 'legendary') cat = 'legendary';
    else if (item.rarity === 'epic') cat = 'epic';
    else cat = 'main';
  }

  let allowed = item.allowedCategories;
  if (!allowed) {
    if (cat === 'legendary' || item.rarity === 'legendary') {
      allowed = ['legendary'];
    } else if (cat === 'epic' || item.rarity === 'epic') {
      allowed = ['epic'];
    } else if (cat === 'weekly') {
      allowed = ['weekly', 'main'];
    } else if (cat === 'side') {
      allowed = ['side', 'main'];
    } else if (cat === 'maintenance') {
      allowed = ['maintenance', 'side'];
    } else {
      allowed = ['main', 'weekly', 'side'];
    }
  }

  const skillFocus = item.skillFocus || (item.tags && item.tags[1]) || item.skillId || item.domain;

  return {
    ...item,
    conceptId: conceptKey,
    variationFamily,
    category: cat as any,
    allowedCategories: allowed as any,
    skillFocus,
  };
}

export const QUEST_LIBRARY: QuestLibraryItem[] = RAW_QUEST_LIBRARY.map(enrichLibraryItem);

/**
 * Utility helper to get library items by domain
 */
export function getQuestsByDomain(domain: DevelopmentDomain): QuestLibraryItem[] {
  return QUEST_LIBRARY.filter(item => item.domain === domain);
}

/**
 * Utility helper to get library items by development tier
 */
export function getQuestsByTier(tier: number): QuestLibraryItem[] {
  return QUEST_LIBRARY.filter(item => item.developmentTier === tier);
}
